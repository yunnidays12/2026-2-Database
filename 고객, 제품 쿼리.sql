CREATE TABLE 고객 (
	이름	VARCHAR(10)  NOT NULL,
  	아이디 VARCHAR(20) not NULL,
  	나이 INT,
    성별 CHAR(1),
  	포인트 INT,
  	PRIMARY KEY (아이디)
);

CREATE TABLE 제품 (
	제품명 VARCHAR(30) NOT NULL,
  	제품번호 VARCHAR(16) NOT NULL,
  	재고 INT,
  	단가 INT,
  	납품회사 VARCHAR(30) NOT NULL,
  	PRIMARY KEY(제품번호),
  	CHECK (재고 <= 3000)
);

-- [2차문제1] 주문 릴레이션 생성
CREATE TABLE 주문 (
	주문번호	VARCHAR(16) NOT NULL,
  	아이디		VARCHAR(20),
  	제품번호	VARCHAR(16),
  	주문수량	INT NOT NULL,
  	주문일자	DATE NOT NULL,
  	PRIMARY KEY(주문번호),
  	FOREIGN KEY (아이디) REFERENCES 고객(아이디),
  	FOREIGN KEY (제품번호) REFERENCES 제품(제품번호)
);

